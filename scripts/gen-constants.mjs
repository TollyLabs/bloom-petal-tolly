#!/usr/bin/env node
// Generates route/src/constants.rs and vendors chain/arc.testnet.json from the
// TOLLY frontend's own sources, so an address change in the monorepo shows up
// as a diff in the Petal in the same PR:
//
//   public/testnet.json        TOLLY deployment (USDC, PAD, FURNACE, routers, ...)
//   src/data/chains.ts         shared Uniswap V3 infrastructure for Arc (INFRA[ARC])
//   src/data/venues.ts         QuoterV2
//   src/data/v4Execution.ts    V4 quoter / UniversalRouter / Permit2 / native currency
//
// No dependencies. Run from anywhere:
//   node petals/tolly/scripts/gen-constants.mjs            # monorepo layout
//   TOLLY_REPO=/path/to/tolly node scripts/gen-constants.mjs
//
// `cargo test` (constants_tests) re-checks the vendored copy against the
// generated constants and, when the monorepo file is present, against it too.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const petalRoot = resolve(here, '..');
const repo = process.env.TOLLY_REPO ? resolve(process.env.TOLLY_REPO) : resolve(petalRoot, '..', '..');

const testnetPath = join(repo, 'public', 'testnet.json');
const testnetBytes = readFileSync(testnetPath);
const testnet = JSON.parse(testnetBytes.toString('utf8'));
const chainsTs = readFileSync(join(repo, 'src', 'data', 'chains.ts'), 'utf8');
const venuesTs = readFileSync(join(repo, 'src', 'data', 'venues.ts'), 'utf8');
const v4Ts = readFileSync(join(repo, 'src', 'data', 'v4Execution.ts'), 'utf8');

const ADDRESS = /^0x[0-9a-fA-F]{40}$/;
function addr(name, value) {
  if (typeof value !== 'string' || !ADDRESS.test(value)) throw new Error(`${name}: not an address: ${value}`);
  return value.slice(2).toLowerCase();
}
function tsField(source, field, label) {
  // Only the Arc block carries these fields with a `0x…` literal beside `as Address`.
  const arcBlock = source.slice(source.indexOf('[ARC]: {'), source.indexOf('[ARC_TESTNET]: {'));
  const m = arcBlock.match(new RegExp(`${field}:\\s*'(0x[0-9a-fA-F]{40})' as Address`));
  if (!m) throw new Error(`${label}: field ${field} not found in the Arc INFRA block`);
  return m[1];
}
function tsConst(source, name, label) {
  const m = source.match(new RegExp(`export const ${name}(?::\\s*Address)?\\s*=\\s*'(0x[0-9a-fA-F]{40})'`));
  if (!m) throw new Error(`${label}: const ${name} not found`);
  return m[1];
}

if (testnet.CHAIN_ID !== 5042) throw new Error(`unexpected CHAIN_ID ${testnet.CHAIN_ID}; the Petal is Arc-only`);

const constants = {
  USDC: addr('USDC', testnet.USDC),
  PAD: addr('PAD', testnet.PAD),
  FURNACE: addr('FURNACE', testnet.FURNACE),
  MULTI_ROUTER: addr('MULTI_ROUTER', testnet.MULTI_ROUTER),
  TOLLY_SWAP_ROUTER: addr('TOLLY_SWAP_ROUTER', testnet.TOLLY_SWAP_ROUTER),
  V4_ROUTER: addr('V4_ROUTER', testnet.V4_ROUTER),
  LOCKER: addr('LOCKER', testnet.LOCKER),
  TOLLY: addr('TOLLY', testnet.TOLLY),
  SWAP_ROUTER02: addr('swapRouter', tsField(chainsTs, 'swapRouter', 'chains.ts')),
  V3_FACTORY: addr('v3Factory', tsField(chainsTs, 'v3Factory', 'chains.ts')),
  POSITION_MANAGER: addr('positionManager', tsField(chainsTs, 'positionManager', 'chains.ts')),
  QUOTER_V2: addr('QUOTER_V2', tsConst(venuesTs, 'QUOTER_V2', 'venues.ts')),
  V4_QUOTER: addr('ARC_V4_QUOTER', tsConst(v4Ts, 'ARC_V4_QUOTER', 'v4Execution.ts')),
  UNIVERSAL_ROUTER: addr('ARC_V4_UNIVERSAL_ROUTER', tsConst(v4Ts, 'ARC_V4_UNIVERSAL_ROUTER', 'v4Execution.ts')),
  PERMIT2: addr('ARC_PERMIT2', tsConst(v4Ts, 'ARC_PERMIT2', 'v4Execution.ts')),
  V4_NATIVE_CURRENCY: addr('V4_NATIVE_CURRENCY', tsConst(v4Ts, 'V4_NATIVE_CURRENCY', 'v4Execution.ts')),
};
// chains.ts and testnet.json both carry the TOLLY routers; they must agree.
if (addr('tollyRouter', tsField(chainsTs, 'tollyRouter', 'chains.ts')) !== constants.TOLLY_SWAP_ROUTER) throw new Error('tollyRouter drift between chains.ts and testnet.json');
if (addr('multiRouter', tsField(chainsTs, 'multiRouter', 'chains.ts')) !== constants.MULTI_ROUTER) throw new Error('multiRouter drift between chains.ts and testnet.json');
if (!/^0x[0-9a-f]{64}$/i.test(testnet.V4_ROUTER_CODEHASH)) throw new Error('V4_ROUTER_CODEHASH is not bytes32');

const digest = createHash('sha256').update(testnetBytes).digest('hex');

const lines = [];
lines.push('// GENERATED by scripts/gen-constants.mjs from public/testnet.json,');
lines.push('// src/data/chains.ts, src/data/venues.ts and src/data/v4Execution.ts.');
lines.push('// Do not edit; re-run the generator and commit the diff.');
lines.push('//');
lines.push('// Arc mainnet (chain id 5042). Despite its filename, public/testnet.json IS');
lines.push('// the served mainnet overlay (`kind: "public"`).');
lines.push('');
lines.push('use alloy_primitives::{Address, address};');
lines.push('');
lines.push('/// Bloom chain key used for `bloom:chain` reads and the tx outbox.');
lines.push('pub const CHAIN: &str = "arc";');
lines.push(`pub const CHAIN_ID: u64 = ${testnet.CHAIN_ID};`);
lines.push(`pub const EXPLORER: &str = ${JSON.stringify(testnet.explorer)};`);
lines.push('');
lines.push('/// TOLLY public API bases. Stage carries an `/api` prefix, prod does not.');
lines.push('pub const API_STAGE: &str = "https://stage.tollylabs.com/api";');
lines.push(`pub const API_PROD: &str = ${JSON.stringify(testnet.api)};`);
lines.push('');
lines.push('/// USDC ERC-20 view (6 decimals). The same balance is the 18-decimal native gas asset.');
lines.push(`pub const USDC: Address = address!("${constants.USDC}");`);
lines.push('pub const USDC_ERC20_DECIMALS: u32 = 6;');
lines.push('pub const NATIVE_DECIMALS: u32 = 18;');
lines.push('/// V4 PoolKey currency for native-quote pools (18-decimal native USDC).');
lines.push(`pub const V4_NATIVE_CURRENCY: Address = address!("${constants.V4_NATIVE_CURRENCY}");`);
lines.push('');
lines.push('/// TollyPad: launches and the `tokens(address)` registry ("is it ours").');
lines.push(`pub const PAD: Address = address!("${constants.PAD}");`);
lines.push('/// Furnace: receives the interface fee (through the routers).');
lines.push(`pub const FURNACE: Address = address!("${constants.FURNACE}");`);
lines.push('/// TollyMultiRouter (V3 + V2): `swapWithToll` / `swapWithTollV2` / `tollFor`.');
lines.push(`pub const MULTI_ROUTER: Address = address!("${constants.MULTI_ROUTER}");`);
lines.push('/// TollySwapRouter (V3 only). Not used for execution; MULTI_ROUTER is preferred.');
lines.push(`pub const TOLLY_SWAP_ROUTER: Address = address!("${constants.TOLLY_SWAP_ROUTER}");`);
lines.push('/// TollyV4Router (follow-up; not executed day-1).');
lines.push(`pub const V4_ROUTER: Address = address!("${constants.V4_ROUTER}");`);
// Long literals are wrapped the way rustfmt wraps them, so the generated file is fmt-stable.
lines.push(`pub const V4_ROUTER_CODEHASH: &str =\n    ${JSON.stringify(testnet.V4_ROUTER_CODEHASH.toLowerCase())};`);
lines.push(`pub const LOCKER: Address = address!("${constants.LOCKER}");`);
lines.push(`pub const TOLLY: Address = address!("${constants.TOLLY}");`);
lines.push('');
lines.push('/// Shared Uniswap V3 infrastructure on Arc (not deployed by TOLLY).');
lines.push(`pub const SWAP_ROUTER02: Address = address!("${constants.SWAP_ROUTER02}");`);
lines.push(`pub const V3_FACTORY: Address = address!("${constants.V3_FACTORY}");`);
lines.push(`pub const POSITION_MANAGER: Address = address!("${constants.POSITION_MANAGER}");`);
lines.push(`pub const QUOTER_V2: Address = address!("${constants.QUOTER_V2}");`);
lines.push('');
lines.push('/// Uniswap V4 on Arc (quoting only, day-1).');
lines.push(`pub const V4_QUOTER: Address = address!("${constants.V4_QUOTER}");`);
lines.push(`pub const UNIVERSAL_ROUTER: Address = address!("${constants.UNIVERSAL_ROUTER}");`);
lines.push(`pub const PERMIT2: Address = address!("${constants.PERMIT2}");`);
lines.push('');
lines.push('/// Interface fee in basis points of the input (buys of external tokens only).');
lines.push('pub const INTERFACE_FEE_BPS: u64 = 20;');
lines.push('/// Every TollyPad pool is immutable at the 1% tier.');
lines.push('pub const POOL_FEE_PAD: u32 = 10_000;');
lines.push('/// TollyPad total supply, 1e27 raw (1B tokens at 18 decimals).');
lines.push('pub const PAD_TOTAL_SUPPLY_RAW: &str = "1000000000000000000000000000";');
lines.push('pub const PAD_TOKEN_DECIMALS: u32 = 18;');
lines.push('');
lines.push('/// sha256 of the vendored `chain/arc.testnet.json` (= public/testnet.json at generation time).');
lines.push(`pub const SOURCE_DIGEST: &str =\n    "sha256:${digest}";`);
lines.push('');

mkdirSync(join(petalRoot, 'chain'), { recursive: true });
writeFileSync(join(petalRoot, 'chain', 'arc.testnet.json'), testnetBytes);
writeFileSync(join(petalRoot, 'route', 'src', 'constants.rs'), lines.join('\n'));
console.log(`wrote route/src/constants.rs and chain/arc.testnet.json (sha256:${digest})`);
