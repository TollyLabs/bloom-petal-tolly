# eth-abi 2.x pads an EMPTY `bytes`/`string` with one extra zero word. The ABI
# spec (`enc(len) pad_right(X)`, padding to a multiple of 32 -> zero bytes for
# an empty value), Solidity's encoder, viem and Foundry's `cast` all emit the
# length word alone. Patch the two encoders so the fixtures follow the spec;
# `cast abi-encode "f(string)" ""` is asserted below when cast is installed.
def _spec_encode_bytes(cls, value):
    cls.validate_value(value)
    padded = value + b"\x00" * ((32 - len(value) % 32) % 32)
    return len(value).to_bytes(32, "big") + padded


_abi_encoding.ByteStringEncoder.encode = classmethod(_spec_encode_bytes)
_abi_encoding.TextStringEncoder.encode = classmethod(
    lambda cls, value: _spec_encode_bytes(_abi_encoding.ByteStringEncoder, value.encode("utf8"))
)

