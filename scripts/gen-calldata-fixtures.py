def selector(sig: str) -> bytes:
    return keccak(text=sig)[:4]


def call(sig: str, types, values) -> str:
    return "0x" + (selector(sig) + encode(types, values)).hex()


def ipfs_uri_for_sha256(sha256_hex: str) -> str:
    # Mirror of src/data/launchLogo.ts#ipfsUriForSha256: CIDv1 raw + sha2-256
    # multihash, base32 lower, no padding, multibase prefix 'b'.
    raw = bytes([0x01, 0x55, 0x12, 0x20]) + bytes.fromhex(sha256_hex)
    return "ipfs://b" + base64.b32encode(raw).decode().lower().rstrip("=")


